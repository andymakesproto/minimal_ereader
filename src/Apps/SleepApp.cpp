void SleepApp::onButtonEvent(int btnId, int eventType) {
    if (eventType != 0) return;

    // Rate limiter to prevent rapid bouncing
    if (millis() - lastWakeAttempt < 500) return;
    lastWakeAttempt = millis();

    // Any button wakes the device up and goes to the Library
    ctx->appManager->switchApp(libraryApp);
}