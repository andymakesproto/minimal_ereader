void SleepApp::onStart() {
    ctx->display->startFullUpdate(); 
    
    // 1. Define your new image dimensions
    int imgWidth = 128;  // Update these to match your new array
    int imgHeight = 128; 
    
    // 2. Fetch screen dimensions from the display controller
    // (Assuming your display controller is configured for 122x250 or similar)
    int screenWidth = ctx->display->getWidth();  
    int screenHeight = ctx->display->getHeight();

    // 3. Calculate the centered X coordinate for the image
    int imgX = (screenWidth - imgWidth) / 2;
    
    // 4. Calculate the Y coordinate to place it in the upper-middle half
    int imgY = (screenHeight - imgHeight) / 2 - 30;  // Adjusted to move it slightly up for better visual balance

    // 5. Define text parameters
    String sleepText = "Minimal Reader";
    // A 9pt FreeMono character is roughly 11 pixels wide
    int textPixelWidth = sleepText.length() * 11; 
    
    // 6. Calculate the centered X coordinate for the text
    int textX = (screenWidth - textPixelWidth) / 2;
    // Place text comfortably below the image
    int textY = imgY + imgHeight + 30; 

    do {
        ctx->display->fillWhite();
        
        // Pass the calculated coordinates and the new array
        ctx->display->drawBitmap(imgX, imgY, book_icon, imgWidth, imgHeight);
        
        ctx->display->setMenuFont();
        ctx->display->drawString(textX, textY, sleepText);
        
    } while (ctx->display->nextPage());
}

